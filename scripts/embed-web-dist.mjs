#!/usr/bin/env node
// Bakes the built web shell (apps/web/dist) into
// apps/server/src/web-assets.generated.ts as base64 entries, so
// `bun build --compile apps/server/src/binary.ts` produces a single
// self-contained binary — no web dist on disk at runtime.
//
//   pnpm --filter @nfi/web build && node scripts/embed-web-dist.mjs
//
// The generated module is committed as an empty stub; this script refills it
// before release builds. Run from the repo root.
//
// SPDX-FileCopyrightText: 2026 Laode Muhammad Al Fatih <lamualfa@gmail.com>
// SPDX-License-Identifier: SSPL-1.0

import { readdir, readFile, stat, writeFile } from "node:fs/promises"
import { join, relative, sep } from "node:path"

const ROOT = new URL("..", import.meta.url).pathname
const DIST = join(ROOT, "apps/web/dist")
const OUT = join(ROOT, "apps/server/src/web-assets.generated.ts")

const walk = async (dir) => {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) files.push(...(await walk(full)))
    else if ((await stat(full)).isFile()) files.push(full)
  }
  return files
}

const files = (await walk(DIST)).sort()
if (files.length === 0) {
  console.error(`no files under ${DIST} — build the web app first (pnpm --filter @nfi/web build)`)
  process.exit(1)
}

const entries = []
for (const file of files) {
  // URL-style keys ("/assets/index-AbC.js"); base64 keeps the generated
  // module free of escaping hazards regardless of file type.
  const key = "/" + relative(DIST, file).split(sep).join("/")
  const body = (await readFile(file)).toString("base64")
  entries.push(`  ${JSON.stringify(key)}: { body: ${JSON.stringify(body)}, base64: true },`)
}

const out = `// SPDX-FileCopyrightText: 2026 Laode Muhammad Al Fatih <lamualfa@gmail.com>
// SPDX-License-Identifier: SSPL-1.0

// GENERATED by scripts/embed-web-dist.mjs — do not edit by hand. This
// committed copy is an empty stub; release builds regenerate it from
// apps/web/dist before compiling the single-file binary.

export const webAssets: Record<string, { body: string; base64: boolean }> = {
${entries.join("\n")}
}
`

await writeFile(OUT, out)
console.log(`embedded ${files.length} web files into ${relative(ROOT, OUT)}`)
